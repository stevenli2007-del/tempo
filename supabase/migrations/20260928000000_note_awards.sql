-- P0-5-4 · 音符储值
--
-- 🔴【Steven 手动】执行方式：Supabase Dashboard → 左侧 SQL Editor → 粘贴执行。
--    顺序：① 跑本 SQL → ② Bud 写代码 + 推 → ③ Vercel 部署 → ④ 探针确认。
--    没跑的表现：记入时 PostgREST 回 `42P01 relation "public.note_awards" does not exist`
--    —— 记入失败是**静默**的（音符是辅助信息，失败不阻断页面），所以更要先看表在不在。
--
-- ---------------------------------------------------------------------------
-- 这张表记什么
-- ---------------------------------------------------------------------------
-- 「某条任务已经为这个用户挣到过一枚音符」——**只记这个事实**，不记积分、不记余额、
-- 不接任何第三方。展示层的数字 = 本表的行数（`count(*)`），没有第二个真相源。
--
-- ---------------------------------------------------------------------------
-- 🔴 为什么主键是 (user_id, task_id)：幂等由**结构**保证，不靠代码小心
-- ---------------------------------------------------------------------------
-- 卡面验收 ② 要求「同一条任务重复确认不重复计分」。若靠代码先查再插，
-- 两个并发请求（快速连点两次勾选）都会查到"没有"、然后都插入；
-- 即便不并发，将来换个调用方也容易漏掉那次先查。
-- 主键冲突让第二次插入根本写不进去 —— 幂等是**数据库**的性质，不是某个函数的性质。
--
-- ---------------------------------------------------------------------------
-- 🔴 为什么**不加** task_id → tasks 的外键
-- ---------------------------------------------------------------------------
-- 考试派生任务是**物理删后重建**的（`lib/parse/persist.ts` 的 `replaceAll()`，
-- 与 P0-3-31「复习数据键不能用 exam_dates.id」同源）：syllabus 重新解析时
-- 那一批任务行被删掉、换一批新 uuid 重新插入。若带 `on delete cascade`，
-- 已挣到的音符会跟着被删 —— **用户的历史记录凭空缩水**，这是最伤信任的一类事故。
-- 不带外键的代价：任务行被物理删后，这里留一行孤儿（不影响计数语义：
-- 那件事确实完成过）。两害相权，宁可留孤儿，不可缩水。
--
-- ---------------------------------------------------------------------------
-- 🔴 已知边界（如实记着，不藏）
-- ---------------------------------------------------------------------------
-- 同一场考试在 syllabus 重解析后换 uuid → 会被当作**新的**一条再记一枚。
-- 与 P0-3-31 / P0-3-34 同源（键跟着 uuid 走就会这样），Phase 0 不为此加复杂度。
-- =============================================================

create table if not exists public.note_awards (
  user_id uuid not null references auth.users (id) on delete cascade,
  task_id uuid not null,
  -- 首次记入的时刻。取消勾选**不删这一行**（见下），所以它是"第一次完成于"，不是"当前状态"。
  awarded_at timestamptz not null default now(),
  primary key (user_id, task_id)
);

comment on table public.note_awards is
  'P0-5-4 音符储值：一行 = 一条任务为这个用户挣到过一枚音符。展示数字 = count(*)。取消勾选不删行（倒扣即惩罚，ADR-016 R5）。';
comment on column public.note_awards.task_id is
  '刻意无外键：考试派生任务在 syllabus 重解析时被物理删重建，带 cascade 会让已挣到的音符跟着消失。';

-- 计数查询只按 user_id 过滤，PK 的**前导列**正是 user_id，已有索引，无需另建。

-- ---------- RLS ----------

alter table public.note_awards enable row level security;

-- 归属判据只有一处（`user_id` 直接等于当前用户，不经 courses 绕）：
-- 这张表不挂课程，走 `courses.user_id` 子查询反而是多余的 JOIN。
drop policy if exists note_awards_owner_all on public.note_awards;
create policy note_awards_owner_all on public.note_awards
  for all
  using (user_id = auth.uid())
  with check (user_id = auth.uid());
