/**
 * 路径参数的校验。
 *
 * 单独成文件是因为第四处出现了同一条 UUID 正则 —— 之前它散在
 * `courses/[id]`、`courses/[id]/syllabus`、`syllabi/[id]/download` 三个路由里各写一份。
 * 路径参数校验规则必须全局一致（否则同一个 id 在不同端点可能被判成不同的错），
 * 所以抽到这里，四处共用。
 */

/**
 * UUID 格式校验。
 *
 * 为什么要在业务查询**之前**先过一遍格式：否则非法 id 会被拼进 SQL/PostgREST 查询，
 * 轻则报 500（跟真的服务端错误混在一起），重则在某些过滤器下产生非预期行为。
 * 格式不对就该是 400 `bad_request`，不是 404，更不是 500。
 *
 * 覆盖了 v1~v5 的通用形状（`8-4-4-4-12` 十六进制），不校验版本号位 ——
 * 我们只用它挡住明显不是 id 的输入，真正的存在性判定交给数据库。
 */
export const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i
